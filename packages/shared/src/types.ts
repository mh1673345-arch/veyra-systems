/**
 * One booking lifecycle, with two entry paths rather than two parallel
 * universes (see `mode`):
 *
 *   request mode:  draft → submitted → reviewing → confirmed | declined | cancelled
 *   calendar mode: awaiting_confirmation → confirmed | cancelled | declined
 *
 * An availability check creates no booking row at all — it is a read — so
 * there is no "availability_checked" status to contradict the others. A
 * reschedule keeps the booking `confirmed` and moves its times, recorded in
 * the audit trail, so a booking is never briefly in a state that says it is
 * not booked when it is.
 */
export type AppointmentStatus =
  | "draft"
  | "submitted"
  | "reviewing"
  /** Calendar mode: the slot is held and Veyra is waiting for the caller to say yes. */
  | "awaiting_confirmation"
  | "confirmed"
  | "declined"
  | "cancelled"
  /** Calendar mode: the caller never confirmed and the hold's window passed. */
  | "expired";

/** How a booking was created, and therefore which lifecycle applies. */
export type AppointmentMode = "request" | "calendar";

